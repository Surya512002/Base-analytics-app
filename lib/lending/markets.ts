export function getMarketById(id: string): LendingMarket | null {
  return BASE_LENDING_MARKETS.find((m) => m.id === id) ?? null;
}

export function filterMarkets(options: {
  category?: string;
  protocol?: string;
  query?: string;
  onlyStocks?: boolean;
}): LendingMarket[] {
  let list = [...BASE_LENDING_MARKETS];

  if (options.onlyStocks) {
    list = list.filter((m) => m.isStockFocus);
  }

  if (options.category && options.category !== "all") {
    if (options.category === "stocks") {
      list = list.filter((m) => m.isStockFocus);
    } else if (options.category === "lend") {
      list = list.filter((m) => m.category === "stocks_lend" || m.category === "crypto_lend");
    } else if (options.category === "borrow") {
      list = list.filter((m) => m.category === "stocks_borrow" || m.category === "crypto_borrow");
    } else if (options.category === "stake") {
      list = list.filter((m) => m.category === "stocks_stake" || m.category === "crypto_stake");
    } else if (options.category === "supervaults") {
      list = list.filter((m) => m.protocol === "superform" || m.contractType === "superform_vault");
    } else {
      list = list.filter((m) => m.category === options.category);
    }
  }

  if (options.protocol && options.protocol !== "all") {
    list = list.filter((m) => m.protocol === options.protocol);
  }

  if (options.query) {
    const q = options.query.trim().toLowerCase();
    list = list.filter(
      (m) =>
        m.name.toLowerCase().includes(q) ||
        m.asset.symbol.toLowerCase().includes(q) ||
        m.collateralAsset?.symbol.toLowerCase().includes(q) ||
        m.protocolLabel.toLowerCase().includes(q) ||
        m.badgeText?.toLowerCase().includes(q)
    );
  }

  return list;
}

import { parseAbi } from "viem";

/** ABI for LimitOrderBook v2 (limit buy, take-profit, stop-loss, trailing stop, bracket/OCO, edit-in-place, DCA). */
export const orderBookAbi = parseAbi([
  // config / state
  "function quoteToken() view returns (address)",
  "function quoteDecimals() view returns (uint8)",
  "function keeperFeeBps() view returns (uint16)",
  "function nextOrderId() view returns (uint256)",
  "function nextPlanId() view returns (uint256)",
  "function paused() view returns (bool)",
  "function markets(address stockToken) view returns (address feed, uint8 feedDecimals, uint8 stockDecimals, bool enabled, uint32 maxStaleness, uint16 maxDeviationBps, address adapter, uint128 maxStockIn, uint128 maxQuoteIn)",
  "function currentPrice(address stockToken) view returns (uint256 price, uint256 updatedAt)",
  // order reads
  "function canExecute(uint256 id) view returns (bool)",
  "function canUpdateTrailing(uint256 id) view returns (bool)",
  "function canExecuteDca(uint256 id) view returns (bool)",
  "function ordersOf(address user) view returns (uint256[])",
  "function plansOf(address user) view returns (uint256[])",
  "function getOrder(uint256 id) view returns ((address owner, uint40 expiry, uint8 orderType, uint8 status, uint16 trailBps, address stockToken, uint96 triggerPrice, uint128 amountIn, uint128 minAmountOut, uint96 peakPrice, uint64 linkedId))",
  "function getOrdersRange(uint256 fromId, uint256 toId) view returns (uint256[] ids, (address owner, uint40 expiry, uint8 orderType, uint8 status, uint16 trailBps, address stockToken, uint96 triggerPrice, uint128 amountIn, uint128 minAmountOut, uint96 peakPrice, uint64 linkedId)[] list)",
  "function getPlan(uint256 id) view returns ((address owner, uint8 status, uint16 remaining, uint32 interval, uint40 nextTime, address stockToken, uint96 maxPrice, uint128 amountPerBuy))",
  "function getPlansRange(uint256 fromId, uint256 toId) view returns (uint256[] ids, (address owner, uint8 status, uint16 remaining, uint32 interval, uint40 nextTime, address stockToken, uint96 maxPrice, uint128 amountPerBuy)[] list)",
  // order writes
  "function createOrder(address stockToken, uint8 orderType, uint128 amountIn, uint96 triggerPrice, uint128 minAmountOut, uint40 expiry) returns (uint256 id)",
  "function createTrailingStop(address stockToken, uint128 amountIn, uint16 trailBps, uint128 minAmountOut, uint40 expiry) returns (uint256 id)",
  "function createBracket(address stockToken, uint128 amountIn, uint96 takeProfitPrice, uint96 stopLossPrice, uint128 minOutTakeProfit, uint128 minOutStopLoss, uint40 expiry) returns (uint256 takeProfitId, uint256 stopLossId)",
  "function updateOrder(uint256 id, uint96 newTriggerPrice, uint128 newMinAmountOut)",
  "function cancelOrder(uint256 id)",
  "function refundExpired(uint256 id)",
  "function executeOrder(uint256 id) returns (uint256 amountOutToOwner)",
  "function updateTrailing(uint256 id) returns (uint96 newStop)",
  // dca writes
  "function createDca(address stockToken, uint128 amountPerBuy, uint16 buys, uint32 interval, uint96 maxPrice) returns (uint256 id)",
  "function executeDca(uint256 id) returns (uint256 stockToOwner)",
  "function cancelDca(uint256 id)",
  // events
  "event OrderCreated(uint256 indexed id, address indexed owner, address indexed stockToken, uint8 orderType, uint256 amountIn, uint256 triggerPrice, uint256 minAmountOut, uint256 expiry)",
  "event BracketCreated(uint256 indexed takeProfitId, uint256 indexed stopLossId)",
  "event OrderUpdated(uint256 indexed id, uint256 triggerPrice, uint256 minAmountOut)",
  "event TrailUpdated(uint256 indexed id, uint256 peakPrice, uint256 stopPrice)",
  "event OrderCancelled(uint256 indexed id, address indexed owner)",
  "event OrderExpired(uint256 indexed id, address indexed owner)",
  "event OrderExecuted(uint256 indexed id, address indexed owner, address indexed keeper, uint256 price, uint256 amountIn, uint256 amountOutToOwner, uint256 keeperFee)",
  "event DcaCreated(uint256 indexed id, address indexed owner, address indexed stockToken, uint256 amountPerBuy, uint256 buys, uint256 interval, uint256 maxPrice)",
  "event DcaExecuted(uint256 indexed id, address indexed owner, address indexed keeper, uint256 price, uint256 amountIn, uint256 stockToOwner, uint256 keeperFee, uint256 remaining)",
  "event DcaCancelled(uint256 indexed id, address indexed owner, uint256 refunded)",
  // custom errors
  "error AlreadyTriggered()",
  "error AmountTooLarge()",
  "error InvalidParams()",
  "error InvalidExpiry()",
  "error InvalidBracket()",
  "error MarketDisabled()",
  "error NotOpen()",
  "error NotOwner()",
  "error NotExpired()",
  "error OrderHasExpired()",
  "error StalePrice()",
  "error NotTriggered()",
  "error Slippage()",
  "error FillBelowOracleBound()",
  "error FeeTooHigh()",
  "error NotTrailing()",
  "error NoTrailUpdate()",
  "error TooEarly()",
  "error PriceAboveCeiling()",
  "error BadPrice()",
  "error FeeOnTransferUnsupported()",
  "error OnlyOrderBook()",
  "error NoPool()",
  // OpenZeppelin standard errors
  "error EnforcedPause()",
  "error ExpectedPause()",
  "error OwnableUnauthorizedAccount(address account)",
  "error SafeERC20FailedOperation(address token)",
  "error ERC20InsufficientBalance(address sender, uint256 balance, uint256 needed)",
  "error ERC20InsufficientAllowance(address spender, uint256 allowance, uint256 needed)",
]);

export const erc20Abi = parseAbi([
  "function decimals() view returns (uint8)",
  "function symbol() view returns (string)",
  "function balanceOf(address) view returns (uint256)",
  "function allowance(address owner, address spender) view returns (uint256)",
  "function approve(address spender, uint256 amount) returns (bool)",
]);
